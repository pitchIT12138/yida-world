import type { Answer, AnswerSource, ContentDetail } from '../lib/types';
import knowledge from './sources/knowledge.json';
import story from './sources/story.json';
export function fromContent(detail:ContentDetail,kind:'knowledge'|'story'):AnswerSource{
  const id=kind+'-'+detail.work_id;
  const lines=detail.content.split(/\n\s*\n|\n/).map(x=>x.trim()).filter(Boolean);
  const grouped=lines.length>60?[...lines.slice(0,59),lines.slice(59).join('\n')]:lines;
  return {id,title:detail.chapter_name,author:detail.author_name||'作者信息未提供',bio:'知乎官方内容 · 返回片段',avatar:(detail.author_name||'知').slice(0,1),origin:kind,workId:detail.work_id,sourceAuthor:detail.author_name,sourceUrl:'https://api.zhihu.com/km-indep-home/hackathon/v2/'+kind+'/'+detail.work_id,excerpt:true,paragraphs:grouped.map((text,i)=>({id:id+'-p'+i,text}))};
}
function original(id:string,title:string,author:string,bio:string,texts:string[],accent:string,tag:string):Answer{
  return {source:{id,title,author,bio,avatar:author.slice(0,1),origin:'original',paragraphs:texts.map((text,i)=>({id:id+'-p'+i,text}))},votes:0,accent,tag};
}
